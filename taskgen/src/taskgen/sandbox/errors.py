"""Ошибки песочницы."""


class SandboxError(RuntimeError):
    """Запуск не состоялся: неизвестное окружение, отказ Piston или нарушение протокола.

    Ошибка в коде кандидата сюда не относится: она возвращается в результате запуска.
    """


class SandboxServiceError(SandboxError):
    """Сам Piston не выполнил запрос: он недоступен или отказал.

    Причина не в запускаемом коде и не в шаблоне, поэтому повтор позже может пройти.
    """
